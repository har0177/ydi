                        contactForm.reset();
                    } else {
                        const errorText = await response.text();
                        throw new Error(errorText || 'Failed to send message');
                    }
                } catch (error) {
                    // Error
                    messageBox.className = 'mb-6 p-4 rounded-xl bg-red-100 dark:bg-red-900/30 border border-red-200 dark:border-red-800';
                    messageBox.innerHTML = '<div class="flex items-center gap-3"><svg class="w-6 h-6 text-red-600 dark:text-red-400" fill="currentColor" viewBox="0 0 20 20"><path fill-rule="evenodd" d="M10 18a8 8 0 100-16 8 8 0 000 16zM8.707 7.293a1 1 0 00-1.414 1.414L8.586 10l-1.293 1.293a1 1 0 101.414 1.414L10 11.414l1.293 1.293a1 1 0 001.414-1.414L11.414 10l1.293-1.293a1 1 0 00-1.414-1.414L10 8.586 8.707 7.293z" clip-rule="evenodd"/></svg><p class="text-red-700 dark:text-red-300 font-medium">' + error.message + '</p></div>';
