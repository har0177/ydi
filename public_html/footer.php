                    const formData = new FormData(contactForm);
                    const response = await fetch('send_email.php', {
                        method: 'POST',
                        body: formData
                    });

                    if (response.ok) {
                        // Success
                        messageBox.className = 'mb-6 p-4 rounded-xl bg-green-100 dark:bg-green-900/30 border border-green-200 dark:border-green-800';
